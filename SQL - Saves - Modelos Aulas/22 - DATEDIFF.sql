
USE ContosoRetailDW

-- DATEDIFF (intervalo, data_inicio, data_final)

SELECT
	DATEDIFF(DAY, '2025-03-10', GETDATE()) DIA
	,DATEDIFF(MONTH, '2025-01-10', GETDATE()) MÊS
	,DATEDIFF(YEAR, '2024-03-10', GETDATE()) ANO

SELECT TOP 100
	s.DateKey
	,GETDATE() DATA_ATUAL
	,DATEDIFF(DAY, '2009-01-31', GETDATE()) DIA
	,DATEDIFF(MONTH, '2009-01-31', GETDATE()) MÊS
	,DATEDIFF(YEAR, '2009-01-31', GETDATE()) ANO
FROM FactOnlineSales s
ORDER BY s.DateKey DESC